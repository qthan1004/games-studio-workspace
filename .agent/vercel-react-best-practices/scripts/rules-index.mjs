#!/usr/bin/env node
// rules-index.mjs - build or search a compact index of a rules/ skill folder.
// Zero dependencies. Output is TOON-style text to keep agent token use low.
//
// Usage:
//   node rules-index.mjs build <skillDir> [<skillDir> ...]   write <skillDir>/RULES_INDEX.md
//   node rules-index.mjs find  <skillDir> <query words> [--limit N]
//   node rules-index.mjs check <skillDir>                     exit 1 if RULES_INDEX.md is stale
//
// Rule files: <skillDir>/rules/<prefix>-<name>.md with frontmatter title, impact, impactDescription, tags.
// Sections: <skillDir>/rules/_sections.md with "## N. Title (prefix)" and "**Impact:** X".

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const [, , cmd, ...rest] = process.argv;

function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const out = {};
  if (!m) return out;
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_][\w-]*):\s*(.*)$/);
    if (kv) out[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim();
  }
  return out;
}

function parseSections(dir) {
  const file = path.join(dir, 'rules', '_sections.md');
  const sections = [];
  if (!fs.existsSync(file)) return sections;
  const text = fs.readFileSync(file, 'utf8');
  const re = /^##\s+\d+\.\s+(.+?)\s+\(([\w-]+)\)\s*$([\s\S]*?)(?=^##\s|(?![\s\S]))/gm;
  let m;
  while ((m = re.exec(text))) {
    const impact = (m[3].match(/\*\*Impact:\*\*\s*([^\n]+)/) || [])[1];
    sections.push({ title: m[1].trim(), prefix: m[2], impact: (impact || '').trim() });
  }
  return sections;
}

function loadRules(dir) {
  const rulesDir = path.join(dir, 'rules');
  if (!fs.existsSync(rulesDir)) throw new Error(`no rules/ folder in ${dir}`);
  const files = fs.readdirSync(rulesDir).filter(f => f.endsWith('.md') && !f.startsWith('_')).sort();
  const hash = crypto.createHash('sha1');
  const rules = files.map(f => {
    const text = fs.readFileSync(path.join(rulesDir, f), 'utf8');
    hash.update(f).update(text);
    const fm = parseFrontmatter(text);
    const id = f.replace(/\.md$/, '');
    return {
      id,
      prefix: id.split('-')[0],
      title: fm.title || id,
      impact: fm.impact || '',
      why: fm.impactDescription || '',
      tags: fm.tags || '',
      bytes: Buffer.byteLength(text),
    };
  });
  return { rules, digest: hash.digest('hex').slice(0, 12) };
}

function render(dir) {
  const name = path.basename(path.resolve(dir));
  const { rules, digest } = loadRules(dir);
  const sections = parseSections(dir);
  const known = new Set(sections.map(s => s.prefix));
  for (const p of new Set(rules.map(r => r.prefix))) {
    if (!known.has(p)) sections.push({ title: p, prefix: p, impact: '' });
  }
  const lines = [];
  lines.push(`# RULES_INDEX - ${name}`);
  lines.push('');
  lines.push(`<!-- generated by rules-index.mjs; source-digest: ${digest}; do not edit by hand -->`);
  lines.push('');
  lines.push(`${rules.length} rules. One line per rule: \`id\` - title - why (tags). Open \`rules/<id>.md\` only for rules that match the task.`);
  lines.push('Targeted task: grep this file for the section prefix or a keyword, then open 1-3 rule files.');
  lines.push('Review or audit: read this file as the checklist; open a rule file only when the code plausibly violates it.');
  lines.push('Never load AGENTS.md; it is the compiled human copy of the same rules.');
  for (const s of sections) {
    const group = rules.filter(r => r.prefix === s.prefix);
    if (!group.length) continue;
    lines.push('');
    lines.push(`## ${s.prefix} - ${s.title}${s.impact ? ` (${s.impact})` : ''}`);
    for (const r of group) {
      const why = r.why ? ` - ${r.why}` : '';
      const tags = r.tags ? ` (${r.tags})` : '';
      const imp = r.impact && r.impact !== s.impact ? ` [${r.impact}]` : '';
      lines.push(`- \`${r.id}\`${imp} - ${r.title}${why}${tags}`);
    }
  }
  lines.push('');
  return { text: lines.join('\n'), digest, count: rules.length };
}

function build(dirs) {
  if (!dirs.length) usage(2);
  const rows = [];
  for (const dir of dirs) {
    const { text, digest, count } = render(dir);
    const out = path.join(dir, 'RULES_INDEX.md');
    fs.writeFileSync(out, text, 'utf8');
    rows.push(`  ${path.basename(path.resolve(dir))},${count},${Buffer.byteLength(text)},${digest}`);
  }
  console.log(`built[${rows.length}]{skill,rules,bytes,digest}:`);
  console.log(rows.join('\n'));
}

function check(dir) {
  const out = path.join(dir, 'RULES_INDEX.md');
  const { digest } = loadRules(dir);
  const current = fs.existsSync(out) ? (fs.readFileSync(out, 'utf8').match(/source-digest: (\w+)/) || [])[1] : null;
  if (current === digest) {
    console.log(`index: fresh (${digest})`);
    return;
  }
  console.log(`index: stale (have ${current || 'none'}, want ${digest})`);
  console.log(`next: node rules-index.mjs build ${dir}`);
  process.exit(1);
}

function find(dir, args) {
  let limit = 5;
  const words = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--limit') limit = Number(args[++i]) || 5;
    else words.push(...args[i].toLowerCase().split(/\s+/).filter(Boolean));
  }
  if (!words.length) usage(2);
  const { rules } = loadRules(dir);
  const scored = rules
    .map(r => {
      const hay = `${r.id} ${r.title} ${r.why} ${r.tags}`.toLowerCase();
      const score = words.reduce((s, w) => s + (hay.includes(w) ? (r.tags.toLowerCase().includes(w) ? 2 : 1) : 0), 0);
      return { ...r, score };
    })
    .filter(r => r.score > 0)
    .sort((a, b) => b.score - a.score || a.id.localeCompare(b.id))
    .slice(0, limit);
  if (!scored.length) {
    console.log(`hits: 0 for "${words.join(' ')}"`);
    console.log('next: read RULES_INDEX.md section headers and pick by concern');
    return;
  }
  console.log(`hits[${scored.length}]{id,impact,title}:`);
  for (const r of scored) console.log(`  ${r.id},${r.impact},"${r.title.replace(/"/g, "'")}"`);
  console.log(`next: open rules/${scored[0].id}.md`);
}

function usage(code) {
  console.log('usage: rules-index.mjs build <skillDir>... | find <skillDir> <words> [--limit N] | check <skillDir>');
  process.exit(code);
}

try {
  if (cmd === 'build') build(rest);
  else if (cmd === 'find') find(rest[0], rest.slice(1));
  else if (cmd === 'check') check(rest[0]);
  else usage(cmd ? 2 : 0);
} catch (e) {
  console.log(`error: ${e.message}`);
  process.exit(2);
}
